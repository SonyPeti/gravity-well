// Generates sw.js: the offline cache list + a version hash of all game files.
// Run before every publish: node tools/build-sw.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const FILES = ['index.html', 'style.css', 'audio.js', 'ads.js', 'store.js', 'progress.js', 'galaxy.js', 'challenge.js', 'game.js', 'manifest.json', 'icon.svg', 'assets.json'];
const ASSET_EXT = /\.(png|jpg|svg|wav|mp3)$/;

function walk(dir) {
  return fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true }).flatMap(e => {
    const rel = dir + '/' + e.name;
    if (e.isDirectory()) return walk(rel);
    return ASSET_EXT.test(e.name) ? [rel] : [];
  });
}

// assets.json lets the game load optional art (new enemies, elite icons) only once it exists
const pngs = fs.readdirSync(path.join(ROOT, 'assets')).filter(f => f.endsWith('.png')).sort();
fs.writeFileSync(path.join(ROOT, 'assets.json'), JSON.stringify(pngs));
const files = [...FILES, ...walk('assets')];
const hash = crypto.createHash('sha1');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// AUTO-GENERATED by tools/build-sw.js — do not edit by hand.
const VERSION = '${version}';
const CACHE = 'gravity-well-' + VERSION;
const FILES = ${JSON.stringify(['./', ...files], null, 0).replace(/","/g, '",\n  "')};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith('gravity-well-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Media elements ask for byte ranges; answer them from the cached file (needed on iOS)
async function rangeResponse(req, res) {
  const m = /bytes=(\\d*)-(\\d*)/.exec(req.headers.get('range') || '');
  if (!m) return res;
  const buf = await res.arrayBuffer();
  const start = m[1] ? Number(m[1]) : 0;
  const end = m[2] ? Math.min(Number(m[2]), buf.byteLength - 1) : buf.byteLength - 1;
  return new Response(buf.slice(start, end + 1), {
    status: 206,
    headers: {
      'Content-Type': res.headers.get('Content-Type') || 'audio/mpeg',
      'Content-Range': \`bytes \${start}-\${end}/\${buf.byteLength}\`,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  });
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return req.headers.has('range') ? rangeResponse(req, cached) : cached;
    try { return await fetch(req); }
    catch (err) { return (await caches.match('./')) || Response.error(); }
  })());
});
`;

fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: version ${version}, ${files.length + 1} files cached`);
